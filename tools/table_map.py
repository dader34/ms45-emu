#!/usr/bin/env python
"""Which routines read each calibration item, and what they write: the
"what does this table do" map for BMWeb's tuning page.

    .venv/bin/python tools/table_map.py                       # the car's own pair, to stdout as JSON
    .venv/bin/python tools/table_map.py --js ../inpa-mac-bridge/app/renderer/core/ms45-table-map.js

Every function of the program is scanned the way tools/explain.py scans one
(ms45emu/explain.py, static only: the registers that hold a calibration or
RAM base are followed through the function), and the result is turned
round: for each XDF item, the functions that read it, each with its name
where one is known, the OS task it runs under (walking its callers up) and
the named RAM variables it writes, which is what the item ends up driving.
"""
import argparse
import json
import os
import sys
sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from ms45emu.explain import Explanation                # noqa: E402
from ms45emu.funcmap import FunctionMap, names_path    # noqa: E402
from ms45emu.image import load_named                   # noqa: E402
from ms45emu.protections import _task_of               # noqa: E402
from ms45emu.xdf import Xdf                            # noqa: E402

WRITES_SHOWN = 8


def value_addresses(pair):
    """The RAM addresses BMW's own value table reads (tools/values_map.py):
    BMWeb names those by their logging labels."""
    path = names_path(pair).replace(".json", ".values.json")
    if not os.path.exists(path):
        return set()
    with open(path) as f:
        return {v["address"] for v in json.load(f)["values"].values()}


def build(pair, xdf):
    fm = FunctionMap(pair)
    known = value_addresses(pair)
    readers = {}                                       # item offset -> {function start: Explanation}
    for f in fm.functions:
        ex = Explanation(fm, f, xdf)
        for key, use in ex.cal.items():
            if use.item is None or not any(h in ("R", "idx", "ptr") for _, h, _ in use.sites):
                continue
            readers.setdefault(use.item.offset, {})[f.start] = ex
    # compact: a reader is [start, task index, name or 0, named writes, writes in all]
    tasks = []
    task_of = {}
    names = {}
    out = {}
    for offset, by_fn in sorted(readers.items()):
        entries = []
        for start, ex in sorted(by_fn.items()):
            f = ex.f
            if start not in task_of:
                t = _task_of(fm, f) or ""
                if t not in tasks:
                    tasks.append(t)
                task_of[start] = tasks.index(t)
            # the variables it writes that can be named: by the names file
            # here, by the logging labels of the value table in BMWeb
            writes, wrote = [], 0
            for addr, use in ex.ram.items():
                if not any(h == "W" for _, h, _ in use.sites):
                    continue
                wrote += 1
                if (use.name or addr in known) and len(writes) < WRITES_SHOWN:
                    writes.append(f"{addr:X}")
                    if use.name:
                        names[f"{addr:X}"] = use.name
            entries.append([f"{f.start:X}", task_of[start], f.name or 0, writes, wrote])
        out[f"{offset:X}"] = entries
    return {"program": pair.program_id.decode("latin1"), "tasks": tasks, "vars": names, "items": out}


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--flash")
    ap.add_argument("--mpc")
    ap.add_argument("--xdf", help="the XDF (default: the one images/ holds for the program)")
    ap.add_argument("--js", help="write BMWeb's core/ms45-table-map.js here instead of JSON to stdout")
    args = ap.parse_args()
    pair = load_named(args.flash, args.mpc) if args.flash else load_named("session1clean")
    xdf = Xdf(args.xdf) if args.xdf else Xdf.find(pair)
    if xdf is None:
        sys.exit("no XDF: pass --xdf or put one in images/")
    table = build(pair, xdf)
    items = sum(len(v) for v in table["items"].values())
    print(f"{len(table['items'])} items read by {items} routine uses", file=sys.stderr)
    if args.js:
        with open(args.js, "w") as f:
            f.write("/**\n * @file Which routines of the MS45 program read each calibration item,\n"
                    " * under which OS task, and the RAM variables they write: what a table\n"
                    " * drives, for the tuning page. GENERATED by ms45-emu tools/table_map.py;\n"
                    " * do not edit. items: calibration offset (hex) -> readers, each\n"
                    " * [start (hex), index into tasks, name or 0, RAM addresses it writes\n"
                    " * that have a name (vars here, or a logging label), RAM variables it\n"
                    " * writes in all].\n */\n"
                    "/* exported MS45_TABLE_MAP */\n"
                    f"const MS45_TABLE_MAP = {json.dumps(table, separators=(',', ':'))};\n"
                    "if (typeof module !== 'undefined' && module.exports) module.exports = { MS45_TABLE_MAP };\n")
    else:
        json.dump(table, sys.stdout, indent=1)


if __name__ == "__main__":
    main()
