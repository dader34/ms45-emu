#!/usr/bin/env python3
"""Emit the fast-flasher body as a JS blob for BMWeb's bootstrap builder.

BMWeb installs the resident flasher with one ordinary full program flash: it
splices the body into the external image and the hook word into MPC 0x8, then
signs and checksums the pair the way every full flash does (the body at ext
0xFD26C sits inside signed segment 2, so the signature covers it -- which is
why flasher_gate.build re-signs, and why BMWeb's own flash path is enough).

Rather than hand-copy offsets that move as the flasher body grows, this runs
flasher_gate.build over a BLANK body range and records exactly the bytes it
changed:

  - the external spans it wrote inside [0xFD26C, 0xFFF40) (stamp + gate +
    entry stub + body), as (offset, bytes) runs;
  - the MPC 0x8 hook word.

The checksum/signature bytes build() also rewrites are NOT recorded: BMWeb
redoes those itself from the spliced image, so baking in this one image's
sums would be wrong for any other car. The output is the body only.

    python3 tools/fast_flasher_js.py            # -> ../inpa-mac-bridge/.../fast-flasher-blob.js
    python3 tools/fast_flasher_js.py --stdout   # print it

Re-run whenever the flasher body changes.
"""

import argparse
import datetime
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.dirname(HERE))

import flasher_gate as g  # noqa: E402

DEFAULT_OUT = os.path.normpath(
    os.path.join(
        HERE, "..", "..", "inpa-mac-bridge", "app", "renderer",
        "core", "flash", "fast-flasher-blob.js",
    )
)


def body_runs():
    """(ext_runs, hook_word): what a bootstrap writes, diffed from blank.

    ext_runs is a list of (offset, bytes) over [0xFD26C, 0xFFF40). The input
    is an all-0xFF body range on an otherwise real image, so build()'s own
    blank-range guard passes and the diff is exactly the body.
    """
    from ms45emu.image import load_named
    pair = load_named("session1.livetune6-notraps")
    flash, mpc = bytearray(pair.flash), bytearray(pair.mpc)

    start, end = g.BODY_RANGE
    flash[start:end] = b"\xff" * (end - start)          # ensure blank for the guard
    struct.pack_into(">I", mpc, 8, g.STOCK_HOOK)        # ensure the stock hook

    built_flash, built_mpc = g.build(bytes(flash), bytes(mpc))

    runs = []
    run_start = None
    for i in range(start, end):
        changed = built_flash[i] != 0xFF
        if changed and run_start is None:
            run_start = i
        elif not changed and run_start is not None:
            runs.append((run_start, built_flash[run_start:i]))
            run_start = None
    if run_start is not None:
        runs.append((run_start, built_flash[run_start:end]))

    hook = struct.unpack_from(">I", built_mpc, 8)[0]
    return runs, hook


def render_js(runs, hook):
    total = sum(len(b) for _, b in runs)
    # the stamp build() really writes (stamp_bytes' defaults are v1 on purpose)
    stamp = next(bytes.fromhex(b.hex())[:16] for off, b in runs if off == g.STAMP_AT)
    now = datetime.date.today().isoformat()
    lines = [
        "// GENERATED by ms45-emu tools/fast_flasher_js.py -- do not edit by hand.",
        "// The resident fast flasher's body, for BMWeb's bootstrap builder",
        "// (core/flash/fast-flasher.js bootstrap()). A full flash splices these",
        "// runs into the external image and the hook word into MPC 0x8, then signs",
        "// the pair as any full flash does (the body is inside a signed segment).",
        "//",
        f"// Built {now} from session1.livetune6-notraps; {total} body bytes in "
        f"{len(runs)} run(s). Re-run the tool when the flasher body changes.",
        "/* exported fastFlasherBlob */",
        "",
        "const fastFlasherBlob = {",
        f"  hookAt: 0x8,",
        f"  hookWord: 0x{hook:08x},",
        f"  stamp: '{stamp.hex()}',",
        "  // [extOffset, hex] runs over [0xFD26C, 0xFFF40)",
        "  runs: [",
    ]
    for off, b in runs:
        lines.append(f"    [0x{off:05x}, '{b.hex()}'],")
    lines += [
        "  ],",
        "};",
        "",
        "if (typeof window !== 'undefined') window.fastFlasherBlob = fastFlasherBlob;",
        "if (typeof module !== 'undefined' && module.exports)",
        "  module.exports = { fastFlasherBlob };",
        "",
    ]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=DEFAULT_OUT)
    ap.add_argument("--stdout", action="store_true")
    args = ap.parse_args()

    runs, hook = body_runs()
    js = render_js(runs, hook)
    if args.stdout:
        print(js)
        return
    with open(args.out, "w") as f:
        f.write(js)
    total = sum(len(b) for _, b in runs)
    print(f"wrote {args.out} ({total} body bytes in {len(runs)} run(s), "
          f"hook {hook:#010x})")


if __name__ == "__main__":
    main()
