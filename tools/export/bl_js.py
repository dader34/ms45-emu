"""BL for BMWeb: the ring and the installer body as a generated JS blob.

(Named for BL, which it first emitted; it now emits BL -- BL plus the
park-path hook, tools/bl.py. The blob keeps its name, blBlob.)

Run from the ms45-emu root: .venv/bin/python -m tools.export.bl_js

Writes inpa-mac-bridge/app/renderer/core/generated/bl-blob.js (blBlob):

  installer  the v13 resident body with its write window opened down to
             0x4000 (flasher_body.PERM_LOW, stamp flags bit 2), spliced in
             by a Fast Flash Program exactly as fastFlasherBlob is. Only
             this body can rewrite the 8 KB sector that holds the handoff
             word, so it is the one BMWeb installs BL through.
  ring       what tools/bl.build() adds to the boot region: the bytes over
             [WINDOW_AT, ring end) -- the handoff window, the park window,
             the stamp, the relocate stub and the ring's own body -- plus
             the two patched words (the handoff at 0x4EBC, the park head at
             0x5228) with their stock values, and the guard bl builds
             against (the park call at 0x3828, in the sector nothing
             writes: a loader that parks some other way is refused). The app
             splices these into the DME's OWN boot content, read off the
             DME, so the car's loader build and its programming log are
             kept; nothing else in the boot region changes.
  installerRing
             the ring's installer variant (bl.build(installer=True): the
             same layout, its body's write window opened to 0x4000, stamp
             flags 7). On a BL DME a held line always lands in the ring,
             never in a resident body, so the way back to the stock loader
             goes through this ring: BL swaps it in, then it puts the two
             words back and blanks itself (Restore stock bootloader).
  lateInstaller
             the installer body behind the LATE gate (flasher_gate.LATE_GATE:
             ~2 s of polls, stamp flag bit 5), put on by the DME's own loader
             and entered by a line held after the ring's window -- the way
             to replace a ring that takes a held line and cannot serve
             (docs/bootloader.md 0d).
"""
import datetime
import os
import struct
import sys
from tools import ROOT

from tools.build import bl
from tools.build import flasher_body
from tools.build import flasher_gate
from tools.export import fast_flasher_js
from tools.build.flasher_gate import hook_word

OUT = os.path.normpath(os.path.join(
    ROOT, "..", "inpa-mac-bridge", "app", "renderer", "core", "generated", "bl-blob.js"))
LINE = 64                       # bytes a hex string


def installer_runs(late=False):
    was = flasher_body.PERM_LOW
    flasher_body.PERM_LOW = 0x4000
    flasher_gate.LATE_GATE = late
    try:
        runs, hook = fast_flasher_js.body_runs()
    finally:
        flasher_body.PERM_LOW = was
        flasher_gate.LATE_GATE = False
    # the splice carries the body only -- the ee_write module at 0xFF000
    # does not ride it -- so the body's stamp must not promise EE write
    # (bit 3). The read window (bit 4) is in the body and stays.
    for i, (off, b) in enumerate(runs):
        if off == 0xFD26C and len(b) >= 8:
            b = bytearray(b)
            b[7] = (b[7] & ~0x08) | 0x10
            runs[i] = (off, bytes(b))
    stamp = next(b[:16] for off, b in runs if off == 0xFD26C)
    return runs, hook, bytes(stamp)


def runs_lines(runs):
    lines = []
    for off, b in runs:
        line = f"      [0x{off:05x}, '{bytes(b).hex()}'],"
        if len(line) <= 80:
            lines.append(line)
        else:
            lines += ["      [", f"        0x{off:05x},", f"        '{bytes(b).hex()}',", "      ],"]
    return lines


def ring_span(installer=False, swap=False):
    from ms45emu.image import load_named
    pair = load_named("session1.livetune6-notraps")
    f, _m = bl.build(pair.flash, pair.mpc, installer=installer, swap=swap)
    end = bl.SPAN_END
    while end > bl.WINDOW_AT and f[end - 1] == 0xFF:
        end -= 1
    end = (end + 7) & ~7                      # CHUNK lengths go in 8s
    return bytes(f[bl.WINDOW_AT:end]), bytes(f[bl.STAMP_AT:bl.STAMP_AT + 16])


def hex_lines(b, indent):
    return [f"{indent}'{b[i:i + LINE].hex()}'," for i in range(0, len(b), LINE)]


def main():
    runs, hook, inst_stamp = installer_runs()
    late, late_hook, late_stamp = installer_runs(late=True)
    ring, ring_stamp = ring_span()
    iring, iring_stamp = ring_span(installer=True)
    sring, sring_stamp = ring_span(swap=True)
    now = datetime.date.today().isoformat()
    lines = [
        "// GENERATED by ms45-emu tools/bl_js.py -- do not edit by hand.",
        "// BL, the boot-region flasher ring (ms45-emu docs/bootloader.md), and",
        "// the bench installer body that puts it on a DME. BENCH ONLY.",
        f"// Built {now}. Re-run the tool when the ring or the body changes.",
        "/* exported blBlob */",
        "",
        "const blBlob = {",
        "  // the resident body with the write window opened to 0x4000 (stamp",
        "  // flags bit 2), spliced like fastFlasherBlob by a Fast Flash Program",
        "  installer: {",
        "    hookAt: 0x8,",
        f"    hookWord: 0x{hook:08x},",
        f"    stamp: '{bytes(inst_stamp).hex()}',",
        "    runs: [",
        *runs_lines(runs),
        "    ],",
        "  },",
        "  // the same body behind the LATE gate (~2 s by the time base, stamp",
        "  // flags bit 5, bit 6 = it reads its off switch at ext 0xFFFE0): put on",
        "  // by the DME's own loader, entered by a line held after",
        "  // the ring's window -- past a ring that takes the line and hangs",
        "  lateInstaller: {",
        "    hookAt: 0x8,",
        f"    hookWord: 0x{late_hook:08x},",
        f"    stamp: '{late_stamp.hex()}',",
        "    runs: [",
        *runs_lines(late),
        "    ],",
        "  },",
        "  // the ring over [at, at + length): windows, stamp, stub, body",
        "  ring: {",
        f"    at: 0x{bl.WINDOW_AT:05x},",
        f"    stampAt: 0x{bl.STAMP_AT:05x},",
        f"    stamp: '{ring_stamp.hex()}',",
        "    hex: [",
        *hex_lines(ring, "      "),
        "    ],",
        "  },",
        "  // the ring's installer variant, at the same place: its body may",
        "  // rewrite the 8 KB sector (stamp flags bit 2)",
        "  installerRing: {",
        f"    stamp: '{iring_stamp.hex()}',",
        "    hex: [",
        *hex_lines(iring, "      "),
        "    ],",
        "  },",
        "  // the ring's loader-swap variant: its body may rewrite every boot",
        "  // sector, the reset vector's included (stamp flags bits 2 and 7).",
        "  // BENCH ONLY: tools/build/bootwrite.py",
        "  swapRing: {",
        f"    stamp: '{sring_stamp.hex()}',",
        f"    flag: 0x{bl.SWAP_FLAG:02x},",
        "    hex: [",
        *hex_lines(sring, "      "),
        "    ],",
        "  },",
        "  // the patched stock words, both in the 8 KB sector at 0x4000: the",
        "  // loader's handoff `ba 0x8`, and the park function's head",
        "  patches: [",
        f"    {{ at: 0x{bl.PATCH_AT:05x}, stock: 0x{bl.STOCK_PATCH_WORD:08x}, word: 0x{hook_word(bl.CPU + bl.WINDOW_AT):08x} }},",
        f"    {{ at: 0x{bl.PARK_HOOK_AT:05x}, stock: 0x{bl.STOCK_PARK_HEAD:08x}, word: 0x{hook_word(bl.CPU + bl.PARKWIN_AT):08x} }},",
        "  ],",
        "  // what the loader must hold for the park hook to be right: the call",
        "  // that builds the park function's address (never written), at one of",
        "  // the sites the loader builds place it (bl.PARK_CALL_SITES)",
        f"  guard: {{ at: 0x{bl.PARK_CALL_AT:05x}, words: [0x{bl.PARK_CALL[0]:08x}, 0x{bl.PARK_CALL[1]:08x}], "
        f"sites: [{', '.join(f'0x{at:05x}' for at in bl.PARK_CALL_SITES)}] }},",
        "};",
        "",
        "if (typeof window !== 'undefined') window.blBlob = blBlob;",
        "if (typeof module !== 'undefined' && module.exports)",
        "  module.exports = { blBlob };",
        "",
    ]
    with open(OUT, "w") as fh:
        fh.write("\n".join(lines))
    print(f"wrote {OUT}: installer {sum(len(b) for _, b in runs)} bytes in {len(runs)} runs "
          f"(stamp {bytes(inst_stamp)[:8].hex()}), late installer stamp {late_stamp[:8].hex()}, ring {len(ring)} bytes at {bl.WINDOW_AT:#x} "
          f"(stamp {ring_stamp[:8].hex()}), installer ring {len(iring)} bytes "
          f"(stamp {iring_stamp[:8].hex()}), patches at {bl.PATCH_AT:#x} and {bl.PARK_HOOK_AT:#x}")


if __name__ == "__main__":
    main()
