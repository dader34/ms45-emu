#!/usr/bin/env python
"""Write BMWeb's Comfort-tree group of the single values that are always
live: the ones the live-tune build keeps in RAM of their own (singles.py's
pool), read out of the image's own single-value table, so the list is what
the DME really does and not a profile's guess. Each gets a plain name from
the XDF's description, grouped by the program's naming families.

    .venv/bin/python tools/comfort_live.py [--image session1.livetune7] \
        --js ../inpa-mac-bridge/app/renderer/screens/tuning/comfort-live.js
"""
import argparse
import json
import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))

from ms45emu import singles                             # noqa: E402
from ms45emu.image import load_named                    # noqa: E402
from ms45emu.xdf import Xdf                             # noqa: E402
from comfort_names import name_for                      # noqa: E402  (tools/comfort_names.py)

# the family a symbol's first word puts it in (c_n_max_er -> "n")
FAMILIES = {
    "n": "Engine speed thresholds", "nr": "Engine speed thresholds",
    "maf": "Air mass", "tps": "Throttle position", "pv": "Pedal", "pq": "Manifold pressure",
    "tq": "Torque", "tqi": "Torque", "tqe": "Torque",
    "iga": "Ignition angle", "knk": "Knock control",
    "lam": "Lambda control", "lamb": "Lambda control", "crlc": "Lambda control",
    "vls": "Lambda sensors", "ls": "Lambda sensors", "lsh": "Lambda sensors",
    "mff": "Fuel", "ti": "Fuel", "te": "Fuel",
    "tco": "Coolant temperature", "toil": "Oil temperature", "tia": "Air temperature", "t": "Times and delays",
    "v": "Voltages", "vb": "Battery voltage", "vs": "Road speed",
    "fac": "Factors", "fil": "Filters", "amp": "Amplitudes",
    "abc": "Fault debounce counters", "det": "Fault debounce counters", "inh": "Inhibits",
    "cppwm": "Canister purge", "cps": "Canister purge",
    "seg": "Crank segments and misfire", "mis": "Crank segments and misfire",
    "cam": "VANOS", "vvt": "VANOS", "ecf": "Electric fan", "ecfpwm": "Electric fan", "ac": "Air conditioning",
    "is": "Idle", "aj": "Adaptation",
}


def family(name):
    parts = name.split("_")
    head = parts[1] if parts[0] in ("c", "lc", "ip", "id", "sa") and len(parts) > 1 else parts[0]
    if parts[0] == "lc":
        return "Switches"
    return FAMILIES.get(head, "Other values")


def plain(item):
    named = name_for(item.name)
    if named:
        return named
    d = re.sub(r"\s+", " ", (item.description or "").replace("&quot;", '"')).strip(" .")
    if not re.search(r"[A-Za-z]", d) or d.lower() == item.name.lower():
        return item.name                        # nothing said, or "????": the symbol is honest
    d = d[0].upper() + d[1:]
    if len(d) > 88:
        d = d[:88].rsplit(" ", 1)[0] + "…"
    return d


def build(pair, xdf):
    t = singles.parse_table(pair.flash[singles.TABLE:singles.TABLE + 0x2800])
    subjects = {}
    missed = []
    for offset, (length, _) in sorted(t["pool"].items()):
        item = xdf.at(offset)
        if item is None or item.offset != offset or item.size != length or item.kind != "constant":
            missed.append(offset)
            continue
        subjects.setdefault(family(item.name), []).append([item.name, plain(item)])
    out = [{"name": n, "items": sorted(v, key=lambda e: e[1].lower())} for n, v in sorted(subjects.items())]
    return out, missed


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--image", default="session1.livetune7", help="the live-tune pair in images/ (name)")
    ap.add_argument("--xdf", help="the XDF (default: the one images/ holds for the program)")
    ap.add_argument("--js", required=True, help="write BMWeb's screens/tuning/comfort-live.js here")
    args = ap.parse_args()
    pair = load_named(args.image)
    xdf = Xdf(args.xdf) if args.xdf else Xdf.find(pair)
    if xdf is None:
        sys.exit("no XDF for this program: pass --xdf")
    if not singles.is_patched(pair):
        sys.exit(f"{args.image} carries no single-value table")
    subjects, missed = build(pair, xdf)
    n = sum(len(s["items"]) for s in subjects)
    body = json.dumps(subjects, indent=2, ensure_ascii=False)
    with open(args.js, "w") as f:
        f.write("/**\n"
                " * @file Tuning > Comfort: the single values the live-tune build keeps in\n"
                " * RAM of their own, so an edit of any of them is live at once, with no\n"
                " * limit on how many. GENERATED by ms45-emu tools/comfort_live.py from the\n"
                f" * image's single-value table ({args.image}) and the XDF's descriptions;\n"
                " * do not edit by hand.\n"
                " */\n"
                "/* exported TN_COMFORT_LIVE */\n\n"
                f"const TN_COMFORT_LIVE = {{\n  program: {json.dumps(pair.program_id.decode('latin1'))},\n"
                f"  image: {json.dumps(args.image)},\n  name: 'Always live',\n  count: {n},\n"
                f"  subjects: {body},\n}};\n\n"
                "if (typeof module !== 'undefined' && module.exports) {\n"
                "  module.exports = { TN_COMFORT_LIVE };\n}\n")
    print(f"wrote {args.js}: {n} values in {len(subjects)} subjects"
          + (f"; {len(missed)} pool values without a matching XDF constant: "
             + ", ".join(f"0x{o:X}" for o in missed[:10]) if missed else ""))


if __name__ == "__main__":
    main()
