"""BL15 for BMWeb: the ring and the installer body as a generated JS blob.

(Named for BL14, which it first emitted; it now emits BL15 -- BL14 plus the
park-path hook, tools/bl15.py. The blob keeps its name, bl14Blob.)

Run from the ms45-emu root: .venv/bin/python tools/bl14_js.py

Writes inpa-mac-bridge/app/renderer/core/flash/bl14-blob.js (bl14Blob):

  installer  the v13 resident body with its write window opened down to
             0x4000 (flasher_body.PERM_LOW, stamp flags bit 2), spliced in
             by a Fast Flash Program exactly as fastFlasherBlob is. Only
             this body can rewrite the 8 KB sector that holds the handoff
             word, so it is the one BMWeb installs BL14 through.
  ring       what tools/bl15.build() adds to the boot region: the bytes over
             [WINDOW_AT, ring end) -- the handoff window, the park window,
             the stamp, the relocate stub and the ring's own body -- plus
             the two patched words (the handoff at 0x4EBC, the park head at
             0x5228) with their stock values, and the guard bl15 builds
             against (the park call at 0x3828, in the sector nothing
             writes: a loader that parks some other way is refused). The app
             splices these into the DME's OWN boot content, read off the
             DME, so the car's loader build and its programming log are
             kept; nothing else in the boot region changes.
"""
import datetime
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.dirname(HERE))

import bl14                     # noqa: E402
import bl15                     # noqa: E402
import flasher_body             # noqa: E402
import fast_flasher_js          # noqa: E402
from flasher_gate import hook_word  # noqa: E402

OUT = os.path.normpath(os.path.join(
    HERE, "..", "..", "inpa-mac-bridge", "app", "renderer", "core", "flash", "bl14-blob.js"))
LINE = 64                       # bytes a hex string


def installer_runs():
    was = flasher_body.PERM_LOW
    flasher_body.PERM_LOW = 0x4000
    try:
        return fast_flasher_js.body_runs()
    finally:
        flasher_body.PERM_LOW = was


def ring_span():
    from ms45emu.image import load_named
    pair = load_named("session1.livetune6-notraps")
    f, _m = bl15.build(pair.flash, pair.mpc)
    end = bl15.SPAN_END
    while end > bl15.WINDOW_AT and f[end - 1] == 0xFF:
        end -= 1
    end = (end + 7) & ~7                      # CHUNK lengths go in 8s
    return bytes(f[bl15.WINDOW_AT:end]), bytes(f[bl15.STAMP_AT:bl15.STAMP_AT + 16])


def hex_lines(b, indent):
    return [f"{indent}'{b[i:i + LINE].hex()}'," for i in range(0, len(b), LINE)]


def main():
    runs, hook = installer_runs()
    inst_stamp = next(b[:16] for off, b in runs if off == 0xFD26C)
    ring, ring_stamp = ring_span()
    now = datetime.date.today().isoformat()
    lines = [
        "// GENERATED by ms45-emu tools/bl14_js.py -- do not edit by hand.",
        "// BL15, the boot-region flasher ring (ms45-emu docs/bootloader.md), and",
        "// the bench installer body that puts it on a DME. BENCH ONLY.",
        f"// Built {now}. Re-run the tool when the ring or the body changes.",
        "/* exported bl14Blob */",
        "",
        "const bl14Blob = {",
        "  // the resident body with the write window opened to 0x4000 (stamp",
        "  // flags bit 2), spliced like fastFlasherBlob by a Fast Flash Program",
        "  installer: {",
        "    hookAt: 0x8,",
        f"    hookWord: 0x{hook:08x},",
        f"    stamp: '{bytes(inst_stamp).hex()}',",
        "    runs: [",
    ]
    for off, b in runs:
        line = f"      [0x{off:05x}, '{bytes(b).hex()}'],"
        if len(line) <= 80:
            lines.append(line)
        else:
            lines += ["      [", f"        0x{off:05x},", f"        '{bytes(b).hex()}',", "      ],"]
    lines += [
        "    ],",
        "  },",
        "  // the ring over [at, at + length): windows, stamp, stub, body",
        "  ring: {",
        f"    at: 0x{bl15.WINDOW_AT:05x},",
        f"    stampAt: 0x{bl15.STAMP_AT:05x},",
        f"    stamp: '{ring_stamp.hex()}',",
        "    hex: [",
        *hex_lines(ring, "      "),
        "    ],",
        "  },",
        "  // the patched stock words, both in the 8 KB sector at 0x4000: the",
        "  // loader's handoff `ba 0x8`, and the park function's head",
        "  patches: [",
        f"    {{ at: 0x{bl14.PATCH_AT:05x}, stock: 0x{bl14.STOCK_PATCH_WORD:08x}, word: 0x{hook_word(bl15.CPU + bl15.WINDOW_AT):08x} }},",
        f"    {{ at: 0x{bl15.PARK_HOOK_AT:05x}, stock: 0x{bl15.STOCK_PARK_HEAD:08x}, word: 0x{hook_word(bl15.CPU + bl15.PARKWIN_AT):08x} }},",
        "  ],",
        "  // what the loader must hold for the park hook to be right: the call",
        "  // that builds the park function's address (never written)",
        f"  guard: {{ at: 0x{bl15.PARK_CALL_AT:05x}, words: [0x{bl15.PARK_CALL[0]:08x}, 0x{bl15.PARK_CALL[1]:08x}] }},",
        "};",
        "",
        "if (typeof window !== 'undefined') window.bl14Blob = bl14Blob;",
        "if (typeof module !== 'undefined' && module.exports)",
        "  module.exports = { bl14Blob };",
        "",
    ]
    with open(OUT, "w") as fh:
        fh.write("\n".join(lines))
    print(f"wrote {OUT}: installer {sum(len(b) for _, b in runs)} bytes in {len(runs)} runs "
          f"(stamp {bytes(inst_stamp)[:8].hex()}), ring {len(ring)} bytes at {bl15.WINDOW_AT:#x} "
          f"(stamp {ring_stamp[:8].hex()}), patches at {bl14.PATCH_AT:#x} and {bl15.PARK_HOOK_AT:#x}")


if __name__ == "__main__":
    main()
